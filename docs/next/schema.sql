 IF NEW.deleted_at_ms IS NOT NULL THEN DELETE FROM post_publications WHERE post_id=NEW.id; END IF;
 RETURN NULL;
END $$;
CREATE TRIGGER posts_recycled AFTER UPDATE OF deleted_at_ms ON posts FOR EACH ROW EXECUTE FUNCTION painter_post_recycled();

CREATE FUNCTION painter_media_state() RETURNS trigger LANGUAGE plpgsql VOLATILE AS $$
BEGIN
 IF NEW.id<>OLD.id OR NEW.owner_user_id<>OLD.owner_user_id THEN RAISE EXCEPTION 'media identity immutable' USING ERRCODE='23514'; END IF;
 IF OLD.state='ready' AND (NEW.storage_key<>OLD.storage_key OR NEW.byte_size<>OLD.byte_size OR NEW.sha256 IS DISTINCT FROM OLD.sha256 OR NEW.mime_type<>OLD.mime_type) THEN
  RAISE EXCEPTION 'ready media bytes immutable' USING ERRCODE='23514'; END IF;
 IF NEW.state<>OLD.state AND NOT (
  (OLD.state='staging' AND NEW.state IN('ready','failed','deleting')) OR
  (OLD.state='ready' AND NEW.state='deleting') OR
  (OLD.state='deleting' AND NEW.state IN('deleted','failed')) OR
  (OLD.state='failed' AND NEW.state='deleting')) THEN RAISE EXCEPTION 'invalid media transition' USING ERRCODE='23514'; END IF;
 IF NEW.state IN('deleting','deleted','failed') AND (
  EXISTS(SELECT 1 FROM post_draft_media_refs WHERE media_id=NEW.id) OR
  EXISTS(SELECT 1 FROM post_revision_media_refs WHERE media_id=NEW.id) OR
  EXISTS(SELECT 1 FROM users WHERE avatar_media_id=NEW.id) OR
  EXISTS(SELECT 1 FROM site_profile WHERE avatar_media_id=NEW.id)) THEN
  RAISE EXCEPTION 'media referenced' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER media_state BEFORE UPDATE ON media_assets FOR EACH ROW EXECUTE FUNCTION painter_media_state();
CREATE TRIGGER media_no_delete BEFORE DELETE ON media_assets FOR EACH ROW EXECUTE FUNCTION painter_immutable();

-- Application transaction requirements not representable by row CHECK constraints:
-- * idempotency advisory lock by (actor,operation,key) BEFORE lookup/CAS; same key+different hash ->409.
-- * first create also deduplicates permanently on (author_user_id,client_draft_id).
-- * audit/outbox/success response ledger belong to the same transaction as their business mutation.
-- * publish validates principal + aggregate/draft versions, takes ordered locks, snapshots saved draft,
--   switches publication; projection and GIN changes + search generation commit together.
-- * feed/search/page queries use current publication; generation+result page use ONE statement snapshot.
-- * publication existence checks for comments/likes/bookmarks happen AFTER locking the posts row.
-- * analytics ingestion: validate bounded batch -> INSERT ON CONFLICT DO NOTHING -> COMMIT -> ACK.
-- PostgreSQL sequences are NOT commit order. DO NOT scan WHERE seq>last_seq for aggregation.
-- * analytics worker: SELECT ... WHERE aggregated_at_ms IS NULL ORDER BY received_at_ms,seq LIMIT $n FOR UPDATE SKIP LOCKED;
--   apply metric deltas + scope-visitor INSERT ... ON CONFLICT + mark those rows aggregated_at_ms
--   in ONE transaction. last_seq is an observational MAX only, never the progress/filter boundary.
-- * purge raw only aggregated_at_ms IS NOT NULL + retention + client retry horizon, not seq<=MAX.
-- * outbox worker: claim rows FOR UPDATE SKIP LOCKED, establish lease, commit; network outside TX.
-- * fact consumer: INSERT outbox_consumptions ON CONFLICT DO NOTHING RETURNING; only added rows
--   update business_daily via atomic ON CONFLICT ... DO UPDATE. Ledger+delta share one transaction.
-- Runtime app role is non-owner/non-superuser; migrate role owns DDL. No untrusted SQL/DDL API.
-- No automatic revision purge. A privileged explicit maintenance migration is needed to drop history.
COMMIT;
