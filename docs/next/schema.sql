-- Painter Next PostgreSQL 18 initial schema, 2026-10-21.
-- Driver: github.com/jackc/pgx/v5 v5.11.0 (native pgxpool), no embedded database fallback.
-- Prerequisites: UTF8 database with Unicode LC_CTYPE (e.g. C.UTF-8), pg_trgm available.
-- Verified target: PostgreSQL 18.6. Run this baseline in an empty application schema.
-- IDs/versions/counters and *_at_ms use BIGINT; times are UTC Unix milliseconds.
-- day_key uses DATE in Asia/Shanghai; flags BOOLEAN; structured data JSONB; secrets BYTEA.
-- IMPORTANT application lock order at READ COMMITTED:
-- idempotency advisory key -> policy_barrier SHARE (ordinary) / UPDATE (management) -> actor users (IDs ascending)
-- -> posts (IDs ascending) -> draft/publication/comment -> taxonomy rows -> media (keys ascending)
-- -> relations/audit/outbox. Re-check authorization/publication AFTER locks.
-- Mutating commands lock posts FOR UPDATE and use WHERE version=$expected then version++.
-- Media GC locks media FOR UPDATE, then a NEW SQL statement checks refs and changes state;
-- GC never takes posts locks. Role/disable/site-settings changes lock policy_barrier FOR UPDATE
-- as a separate statement BEFORE users/settings mutations; ordinary writes hold FOR SHARE.
-- Trigger lock/checks are defense in depth, not permission to ignore application lock order.
-- Snapshot construction: under aggregate lock insert child tags/media BEFORE parent revision;
-- deferred FKs require parent by COMMIT; revision advisory lock prevents append/seal races.
-- Rendering/network/disk streaming occurs outside DB transactions; files/DB are not cross-system ACID.
