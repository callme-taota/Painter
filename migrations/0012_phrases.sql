CREATE TABLE phrases (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 text TEXT NOT NULL CHECK(char_length(text) BETWEEN 1 AND 280 AND btrim(text)<>''),
 kind TEXT NOT NULL CHECK(kind IN ('sentence','word')),
 source TEXT NOT NULL DEFAULT '' CHECK(char_length(source)<=120),
 published BOOLEAN NOT NULL DEFAULT false,
 created_at_ms BIGINT NOT NULL,
 updated_at_ms BIGINT NOT NULL
);
CREATE INDEX phrases_public_id ON phrases(id DESC) WHERE published;

