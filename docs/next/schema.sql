CREATE FUNCTION painter_revision_snapshot() RETURNS trigger LANGUAGE plpgsql VOLATILE AS $$
DECLARE d post_drafts%ROWTYPE; category_label text;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtextextended('painter:revision:'||NEW.id,0));
 PERFORM 1 FROM posts WHERE id=NEW.post_id FOR UPDATE;
 SELECT * INTO d FROM post_drafts WHERE post_id=NEW.post_id FOR UPDATE;
 IF NOT FOUND OR d.draft_version<>NEW.source_draft_version OR d.title<>NEW.title OR d.summary<>NEW.summary
 OR d.markdown<>NEW.markdown OR d.category_id IS DISTINCT FROM NEW.category_id THEN
  RAISE EXCEPTION 'revision must snapshot current saved draft' USING ERRCODE='23514';
 END IF;
 IF NEW.category_id IS NOT NULL THEN
  SELECT name INTO category_label FROM categories WHERE id=NEW.category_id FOR SHARE;
  IF NOT FOUND OR category_label IS DISTINCT FROM NEW.category_name THEN RAISE EXCEPTION 'category snapshot mismatch' USING ERRCODE='23514'; END IF;
 END IF;
 -- Application prelocks the complete taxonomy/media set in this same order BEFORE child inserts.
 PERFORM t.id FROM tags t JOIN post_draft_tags dt ON dt.tag_id=t.id WHERE dt.post_id=NEW.post_id ORDER BY t.id FOR SHARE OF t;
 PERFORM m.id FROM media_assets m JOIN post_draft_media_refs dr ON dr.media_id=m.id WHERE dr.post_id=NEW.post_id ORDER BY m.id FOR UPDATE OF m;
 IF EXISTS(SELECT tag_id,tag_name FROM post_revision_tags WHERE revision_id=NEW.id
           EXCEPT SELECT dt.tag_id,t.name FROM post_draft_tags dt JOIN tags t ON t.id=dt.tag_id WHERE dt.post_id=NEW.post_id)
 OR EXISTS(SELECT dt.tag_id,t.name FROM post_draft_tags dt JOIN tags t ON t.id=dt.tag_id WHERE dt.post_id=NEW.post_id
           EXCEPT SELECT tag_id,tag_name FROM post_revision_tags WHERE revision_id=NEW.id) THEN
  RAISE EXCEPTION 'tag snapshot mismatch' USING ERRCODE='23514'; END IF;
 IF EXISTS(SELECT media_id FROM post_revision_media_refs WHERE revision_id=NEW.id EXCEPT SELECT media_id FROM post_draft_media_refs WHERE post_id=NEW.post_id)
 OR EXISTS(SELECT media_id FROM post_draft_media_refs WHERE post_id=NEW.post_id EXCEPT SELECT media_id FROM post_revision_media_refs WHERE revision_id=NEW.id) THEN
  RAISE EXCEPTION 'media snapshot mismatch' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER revisions_snapshot BEFORE INSERT ON post_revisions FOR EACH ROW EXECUTE FUNCTION painter_revision_snapshot();
CREATE TRIGGER revisions_immutable BEFORE UPDATE OR DELETE ON post_revisions FOR EACH ROW EXECUTE FUNCTION painter_immutable();

CREATE FUNCTION painter_publication_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE target bigint; deleted_ms bigint;
BEGIN
 IF TG_OP='DELETE' THEN target:=OLD.post_id; ELSE target:=NEW.post_id; END IF;
 IF TG_OP='UPDATE' AND NEW.post_id<>OLD.post_id THEN RAISE EXCEPTION 'publication identity immutable' USING ERRCODE='23514'; END IF;
 SELECT deleted_at_ms INTO deleted_ms FROM posts WHERE id=target FOR UPDATE;
 IF TG_OP<>'DELETE' AND (NOT FOUND OR deleted_ms IS NOT NULL) THEN RAISE EXCEPTION 'post deleted or missing' USING ERRCODE='23514'; END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER publications_guard BEFORE INSERT OR UPDATE OR DELETE ON post_publications FOR EACH ROW EXECUTE FUNCTION painter_publication_guard();
CREATE FUNCTION painter_search_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM post_publications pub JOIN posts p ON p.id=pub.post_id
 JOIN post_revisions r ON r.id=pub.revision_id AND r.post_id=pub.post_id
 WHERE pub.post_id=NEW.post_id AND pub.revision_id=NEW.revision_id AND p.deleted_at_ms IS NULL
 AND NEW.title=r.search_title AND NEW.summary=r.search_summary AND NEW.body=r.search_body) THEN
  RAISE EXCEPTION 'search requires exact current public revision' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER search_documents_guard BEFORE INSERT OR UPDATE ON search_documents FOR EACH ROW EXECUTE FUNCTION painter_search_guard();
CREATE FUNCTION painter_publication_projection() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE target bigint;
BEGIN
 IF TG_OP='DELETE' THEN target:=OLD.post_id; ELSE target:=NEW.post_id; END IF;
 DELETE FROM search_documents WHERE post_id=target;
 IF TG_OP<>'DELETE' THEN
  INSERT INTO search_documents(post_id,revision_id,title,summary,body)
  SELECT NEW.post_id,r.id,r.search_title,r.search_summary,r.search_body FROM post_revisions r WHERE r.id=NEW.revision_id;
 END IF;
 UPDATE search_state SET generation=generation+1 WHERE id=1;
 IF NOT FOUND THEN RAISE EXCEPTION 'search_state singleton missing' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END $$;
CREATE TRIGGER publications_projection AFTER INSERT OR UPDATE OR DELETE ON post_publications FOR EACH ROW EXECUTE FUNCTION painter_publication_projection();
CREATE FUNCTION painter_post_recycled() RETURNS trigger LANGUAGE plpgsql AS $$
