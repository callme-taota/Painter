-- Products are independent of repository snapshots. Existing homepage_projects
-- remain intact: a repository is not automatically a product.
CREATE TABLE products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug TEXT NOT NULL UNIQUE CHECK(char_length(slug) BETWEEN 1 AND 96 AND slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
 builtin_key TEXT UNIQUE CHECK(builtin_key IS NULL OR builtin_key='painter'),
 name TEXT NOT NULL CHECK(char_length(name) BETWEEN 1 AND 100 AND btrim(name)<>''),
 summary TEXT NOT NULL DEFAULT '' CHECK(char_length(summary)<=600),
 markdown TEXT NOT NULL DEFAULT '' CHECK(octet_length(markdown)<=1048576),
 sanitized_html TEXT NOT NULL DEFAULT '',
 platforms TEXT[] NOT NULL DEFAULT '{}' CHECK(cardinality(platforms)<=12),
 state TEXT NOT NULL DEFAULT 'development' CHECK(state IN('development','available','archived')),
 published BOOLEAN NOT NULL DEFAULT false,
 featured BOOLEAN NOT NULL DEFAULT false,
 position INTEGER NOT NULL DEFAULT 0 CHECK(position BETWEEN 0 AND 1000000),
 links JSONB NOT NULL DEFAULT '{"main":{"type":"web","url":""},"docs_url":"","repositories":[]}' CHECK(jsonb_typeof(links)='object'),
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 created_at_ms BIGINT NOT NULL CHECK(created_at_ms>=0),
 updated_at_ms BIGINT NOT NULL CHECK(updated_at_ms>=created_at_ms),
 deleted_at_ms BIGINT,
 CHECK(deleted_at_ms IS NULL OR (deleted_at_ms>=created_at_ms AND NOT published AND NOT featured))
);
CREATE INDEX products_public_order ON products(position,id) WHERE published AND deleted_at_ms IS NULL;
CREATE TABLE product_media (
 product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
 media_id TEXT NOT NULL REFERENCES media_assets(id) ON DELETE RESTRICT,
 kind TEXT NOT NULL CHECK(kind IN('icon','cover','gallery','body')),
 position INTEGER NOT NULL CHECK(position BETWEEN 0 AND 100),
 PRIMARY KEY(product_id,kind,position),
 UNIQUE(product_id,kind,media_id),
 CHECK(kind IN('gallery','body') OR position=0)
);
CREATE INDEX product_media_ref ON product_media(media_id);
CREATE FUNCTION painter_product_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.id<>OLD.id OR NEW.slug<>OLD.slug OR NEW.builtin_key IS DISTINCT FROM OLD.builtin_key OR NEW.created_at_ms<>OLD.created_at_ms OR NEW.version<>OLD.version+1 OR OLD.deleted_at_ms IS NOT NULL THEN
  RAISE EXCEPTION 'product identity immutable and version must advance once' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER product_guard BEFORE UPDATE ON products FOR EACH ROW EXECUTE FUNCTION painter_product_guard();
CREATE TRIGGER product_media_ready BEFORE INSERT OR UPDATE ON product_media FOR EACH ROW EXECUTE FUNCTION painter_media_reference_ready('media_id');
CREATE FUNCTION painter_product_media_state() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.state IN('deleting','deleted','failed') AND EXISTS(SELECT 1 FROM product_media WHERE media_id=NEW.id) THEN
  RAISE EXCEPTION 'media referenced by a product' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER product_media_state BEFORE UPDATE OF state ON media_assets FOR EACH ROW EXECUTE FUNCTION painter_product_media_state();

