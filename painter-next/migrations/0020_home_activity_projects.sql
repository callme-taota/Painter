-- V24 adds opt-in home sections by read normalization in the application.
-- Existing homepage_settings rows, visibility, ordering and content are untouched.
CREATE INDEX posts_first_public_activity ON posts(first_published_at_ms)
 WHERE deleted_at_ms IS NULL AND first_published_at_ms IS NOT NULL;

CREATE TABLE homepage_projects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source TEXT NOT NULL CHECK(source IN('manual','github')),
 repo_url TEXT NOT NULL DEFAULT '' CHECK(char_length(repo_url)<=300),
 title_override TEXT CHECK(char_length(title_override)<=80),
 description_override TEXT CHECK(char_length(description_override)<=600),
 url_override TEXT CHECK(char_length(url_override)<=2048),
 language_override TEXT CHECK(char_length(language_override)<=80),
 metadata JSONB NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(metadata)='object'),
 position INTEGER NOT NULL DEFAULT 0 CHECK(position BETWEEN 0 AND 1000000),
 visible BOOLEAN NOT NULL DEFAULT false,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 fetched_at_ms BIGINT,
 attempted_at_ms BIGINT,
 last_error TEXT NOT NULL DEFAULT '' CHECK(char_length(last_error)<=240),
 created_at_ms BIGINT NOT NULL,
 updated_at_ms BIGINT NOT NULL,
 CHECK((source='github' AND repo_url<>'') OR (source='manual' AND repo_url=''))
);
CREATE INDEX homepage_projects_order ON homepage_projects(position,id);
CREATE TABLE homepage_project_rates (
 owner_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 window_at_ms BIGINT NOT NULL,
 requests INTEGER NOT NULL CHECK(requests BETWEEN 1 AND 10)
);
DO $$ BEGIN
