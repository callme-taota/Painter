import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import {createContract} from './color-policy.mjs'

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const registry=JSON.parse(fs.readFileSync(path.join(root,'colors.json'),'utf8'))
const {keys}=createContract(registry)
for(const entry of [...Object.values(registry.colors),...Object.values(registry.modes).flatMap(Object.values).map(value=>({light:value,dark:value}))]){
 for(const value of [entry.light,entry.dark]){
  if(/[;{}<>]|\/\*|url\(|expression\(/i.test(value))throw new Error('Unsafe color expression: '+value)
  for(const match of value.matchAll(/var\((--[\w-]+)/g))if(!keys.has(match[1]))throw new Error('Unknown color reference: '+match[1])
 }
}
const banner='Generated from web/colors.json. Run npm run colors:generate; do not edit.'
const declarations=theme=>Object.entries(registry.colors).map(([key,value])=>`--${key}:${value[theme]};`).join('')+Object.entries(registry.aliases).map(([key,target])=>`--${key}:var(--${target});`).join('')
let css=`/* ${banner} */\n:root{color-scheme:light;${declarations('light')}}\n:root[data-theme=dark]{color-scheme:dark;${declarations('dark')}}\n@media(prefers-color-scheme:dark){:root:not([data-theme]){color-scheme:dark;${declarations('dark')}}}\n`
for(const [mode,values]of Object.entries(registry.modes)){
 const query=mode==='print'?'print':'(prefers-contrast:more)'
 css+=`@media ${query}{:root:root{${mode==='print'?'color-scheme:light;'+declarations('light'):''}${Object.entries(values).map(([key,value])=>`--${key}:${value};`).join('')}}}\n`
}
const ts=`// ${banner}\nexport const colorTokens=${JSON.stringify(Object.fromEntries(Object.entries(registry.colors).map(([key,{light,dark}])=>[key,{light,dark}])),null,2)} as const\nexport type ColorKey=keyof typeof colorTokens\nexport type ColorTheme='light'|'dark'\nexport function colorValue(key:ColorKey,theme:ColorTheme='light'):string{return colorTokens[key][theme]}\nexport function colorVar(key:ColorKey):string{return 'var(--'+key+')'}\n`
const goName=key=>'Color'+key.split('-').map(part=>part[0].toUpperCase()+part.slice(1)).join('')
const nameWidth=Math.max(...Object.keys(registry.colors).map(key=>goName(key).length))
const constant=(name,type,value)=>`\t${name.padEnd(nameWidth+1)}${type.padEnd(11)}= ${JSON.stringify(value)}`
const go=`// Code generated by web/frontend/build/color-tokens.mjs; DO NOT EDIT.
package web

type ColorKey string
type ColorTheme string

const (
${constant('Light','ColorTheme','light')}
${constant('Dark','ColorTheme','dark')}
${Object.keys(registry.colors).map(key=>constant(goName(key),'ColorKey',key)).join('\n')}
)

var colorTokens = map[ColorKey][2]string{
${Object.entries(registry.colors).map(([key,value])=>`\t${(goName(key)+':').padEnd(nameWidth+2)}{${JSON.stringify(value.light)}, ${JSON.stringify(value.dark)}},`).join('\n')}
}

// Color returns a registered role, suitable for manifests, canvas or generated artwork.
func Color(key ColorKey, theme ColorTheme) string {
\tpair, ok := colorTokens[key]
\tif !ok {
\t\tpanic("unregistered color key: " + string(key))
\t}
\tif theme == Dark {
\t\treturn pair[1]
\t}
\treturn pair[0]
}
`

const outputs={'frontend/src/color-tokens.css':css,'frontend/src/color-tokens.ts':ts,'colors_generated.go':go}
let stale=false
for(const [file,content]of Object.entries(outputs)){
 const target=path.join(root,file)
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==content){console.error('Stale color tokens: web/'+file);stale=true}}
 else fs.writeFileSync(target,content)
}
if(stale)process.exitCode=1
