-- A serial is an ordered set of references to articles, never another copy of
-- their text. Publication is checked against public_posts at read time so
-- withdrawal/deletion removes chapters and navigation in the same commit.
CREATE TABLE series (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 title TEXT NOT NULL CHECK(char_length(title) BETWEEN 1 AND 120 AND btrim(title)<>''),
 slug TEXT NOT NULL CHECK(char_length(slug) BETWEEN 1 AND 96 AND slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
 description TEXT NOT NULL DEFAULT '' CHECK(char_length(description)<=1200),
 cover_media_id TEXT REFERENCES media_assets(id) ON DELETE RESTRICT,
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN('draft','published')),
 state TEXT NOT NULL DEFAULT 'ongoing' CHECK(state IN('ongoing','completed')),
 created_at_ms BIGINT NOT NULL CHECK(created_at_ms>=0),
 updated_at_ms BIGINT NOT NULL CHECK(updated_at_ms>=created_at_ms),
 deleted_at_ms BIGINT,
 CHECK(deleted_at_ms IS NULL OR (deleted_at_ms>=created_at_ms AND status='draft' AND cover_media_id IS NULL))
);
CREATE UNIQUE INDEX series_slug ON series(slug) WHERE deleted_at_ms IS NULL;
CREATE INDEX series_author_id ON series(author_user_id,id DESC) WHERE deleted_at_ms IS NULL;
CREATE INDEX series_public_id ON series(id DESC) WHERE status='published' AND deleted_at_ms IS NULL;
CREATE INDEX series_cover_ref ON series(cover_media_id) WHERE cover_media_id IS NOT NULL;

CREATE TABLE series_chapters (
 series_id BIGINT NOT NULL REFERENCES series(id) ON DELETE CASCADE,
 post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 position INTEGER NOT NULL CHECK(position BETWEEN 1 AND 300),
 PRIMARY KEY(series_id,post_id),
 UNIQUE(series_id,position)
);
CREATE INDEX series_chapters_post ON series_chapters(post_id,series_id);

CREATE FUNCTION painter_series_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE media_owner bigint; media_state text;
BEGIN
 IF TG_OP='UPDATE' THEN
  IF NEW.id<>OLD.id OR NEW.author_user_id<>OLD.author_user_id OR NEW.created_at_ms<>OLD.created_at_ms OR NEW.version<>OLD.version+1 OR OLD.deleted_at_ms IS NOT NULL THEN
   RAISE EXCEPTION 'series identity immutable and version must advance once' USING ERRCODE='23514';
  END IF;
 END IF;
 IF NEW.cover_media_id IS NOT NULL THEN
  SELECT owner_user_id,state INTO media_owner,media_state FROM media_assets WHERE id=NEW.cover_media_id FOR UPDATE;
  IF media_owner IS DISTINCT FROM NEW.author_user_id OR media_state IS DISTINCT FROM 'ready' THEN
   RAISE EXCEPTION 'series cover must be ready media owned by the author' USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER series_guard BEFORE INSERT OR UPDATE ON series FOR EACH ROW EXECUTE FUNCTION painter_series_guard();

CREATE FUNCTION painter_series_chapter_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE serial_author bigint; article_author bigint; removed bigint;
BEGIN
 SELECT author_user_id,deleted_at_ms INTO serial_author,removed FROM series WHERE id=NEW.series_id FOR UPDATE;
 SELECT author_user_id INTO article_author FROM posts WHERE id=NEW.post_id FOR KEY SHARE;
 IF serial_author IS NULL OR article_author IS DISTINCT FROM serial_author OR removed IS NOT NULL THEN
  RAISE EXCEPTION 'series chapters must belong to the immutable series author' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER series_chapter_guard BEFORE INSERT OR UPDATE ON series_chapters FOR EACH ROW EXECUTE FUNCTION painter_series_chapter_guard();

-- Preserve all existing audit vocabulary without rewriting historical records.
DO $$ DECLARE existing text;
BEGIN
 SELECT pg_get_expr(conbin,conrelid) INTO existing FROM pg_constraint WHERE conrelid='audit_logs'::regclass AND conname='audit_logs_action_check';
 ALTER TABLE audit_logs DROP CONSTRAINT audit_logs_action_check;
 EXECUTE 'ALTER TABLE audit_logs ADD CONSTRAINT audit_logs_action_check CHECK (('||existing||') OR action IN(''series.create'',''series.update'',''series.delete''))';
 SELECT pg_get_expr(conbin,conrelid) INTO existing FROM pg_constraint WHERE conrelid='audit_logs'::regclass AND conname='audit_logs_target_type_check';
 ALTER TABLE audit_logs DROP CONSTRAINT audit_logs_target_type_check;
 EXECUTE 'ALTER TABLE audit_logs ADD CONSTRAINT audit_logs_target_type_check CHECK (('||existing||') OR target_type=''series'')';
 IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='painter_app') THEN
  REVOKE ALL ON series,series_chapters FROM painter_app;
  REVOKE ALL ON SEQUENCE series_id_seq FROM painter_app;
  GRANT SELECT,INSERT,UPDATE ON series TO painter_app;
  GRANT SELECT,INSERT,UPDATE,DELETE ON series_chapters TO painter_app;
  GRANT USAGE ON SEQUENCE series_id_seq TO painter_app;
 END IF;
END $$;
