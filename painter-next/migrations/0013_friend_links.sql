CREATE TABLE friend_links (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL CHECK(char_length(name) BETWEEN 1 AND 80 AND btrim(name)<>''),
 url TEXT NOT NULL CHECK(char_length(url) BETWEEN 1 AND 2048 AND url ~* '^https?://'),
 description TEXT NOT NULL DEFAULT '' CHECK(char_length(description)<=240),
 avatar_url TEXT NOT NULL DEFAULT '' CHECK(char_length(avatar_url)<=2048 AND (avatar_url='' OR avatar_url ~* '^https?://')),
 sort_order INTEGER NOT NULL DEFAULT 0 CHECK(sort_order BETWEEN -100000 AND 100000),
 visible BOOLEAN NOT NULL DEFAULT false,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 created_at_ms BIGINT NOT NULL,
 updated_at_ms BIGINT NOT NULL
);
CREATE INDEX friend_links_public_order ON friend_links(sort_order,id) WHERE visible;

CREATE TABLE friend_link_settings (
 id BIGINT PRIMARY KEY CHECK(id=1),
 enabled BOOLEAN NOT NULL DEFAULT true,
 title TEXT NOT NULL DEFAULT '友链' CHECK(char_length(title) BETWEEN 1 AND 80 AND btrim(title)<>''),
 description TEXT NOT NULL DEFAULT '' CHECK(char_length(description)<=400),
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0)
);
