CREATE TABLE homepage_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind TEXT NOT NULL CHECK(kind IN('steam','music','photos')),
 title TEXT NOT NULL DEFAULT '' CHECK(char_length(title)<=80),
 subtitle TEXT NOT NULL DEFAULT '' CHECK(char_length(subtitle)<=600),
 alt TEXT NOT NULL DEFAULT '' CHECK(char_length(alt)<=200),
 url TEXT NOT NULL DEFAULT '' CHECK(char_length(url)<=2048),
 image_url TEXT NOT NULL DEFAULT '' CHECK(char_length(image_url)<=2048),
 media_id TEXT REFERENCES media_assets(id) ON DELETE RESTRICT,
 provider_id TEXT NOT NULL DEFAULT '' CHECK(char_length(provider_id)<=64),
 source TEXT NOT NULL DEFAULT 'manual' CHECK(source IN('manual','steam_sync')),
 local_override BOOLEAN NOT NULL DEFAULT false,
 position INTEGER NOT NULL DEFAULT 0 CHECK(position BETWEEN 0 AND 1000000),
 visible BOOLEAN NOT NULL DEFAULT true,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 created_at_ms BIGINT NOT NULL,
 updated_at_ms BIGINT NOT NULL,
 CHECK(kind<>'photos' OR media_id IS NOT NULL),
 CHECK(media_id IS NOT NULL OR image_url<>''),
 CHECK(source<>'steam_sync' OR (kind='steam' AND provider_id<>''))
);
CREATE INDEX homepage_items_order ON homepage_items(kind,position,id);
CREATE INDEX homepage_items_media ON homepage_items(media_id) WHERE media_id IS NOT NULL;
CREATE UNIQUE INDEX homepage_items_sync_identity ON homepage_items(kind,source,provider_id) WHERE source='steam_sync';

CREATE TABLE homepage_import_cache (
 kind TEXT NOT NULL CHECK(kind IN('steam','music')),
 provider_id TEXT NOT NULL,
 country TEXT NOT NULL,
 metadata JSONB NOT NULL,
 expires_at_ms BIGINT NOT NULL,
 PRIMARY KEY(kind,provider_id,country)
);
CREATE TABLE homepage_provider_rates (
 owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 provider TEXT NOT NULL CHECK(provider IN('steam','music')),
 window_at_ms BIGINT NOT NULL,
 requests INTEGER NOT NULL CHECK(requests BETWEEN 1 AND 20),
 PRIMARY KEY(owner_id,provider)
);
CREATE INDEX homepage_import_cache_expiry ON homepage_import_cache(expires_at_ms);

CREATE FUNCTION painter_home_media_ready() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE s text; mime text;
BEGIN
 IF NEW.media_id IS NOT NULL THEN
  SELECT state,mime_type INTO s,mime FROM media_assets WHERE id=NEW.media_id FOR UPDATE;
  IF NOT FOUND OR s<>'ready' OR mime NOT IN('image/png','image/jpeg','image/gif','image/webp') THEN
   RAISE EXCEPTION 'homepage cover must be ready image' USING ERRCODE='23514';
  END IF;
 END IF;
 IF TG_OP='UPDATE' AND (NEW.id<>OLD.id OR NEW.kind<>OLD.kind OR NEW.source<>OLD.source) THEN
  RAISE EXCEPTION 'homepage item identity immutable' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER homepage_items_ready BEFORE INSERT OR UPDATE ON homepage_items FOR EACH ROW EXECUTE FUNCTION painter_home_media_ready();
CREATE FUNCTION painter_home_media_state_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.state IN('deleting','deleted','failed') AND EXISTS(SELECT 1 FROM homepage_items WHERE media_id=NEW.id) THEN
  RAISE EXCEPTION 'media referenced by homepage' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER media_home_reference_guard BEFORE UPDATE OF state ON media_assets FOR EACH ROW EXECUTE FUNCTION painter_home_media_state_guard();

