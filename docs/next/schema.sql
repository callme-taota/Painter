-- Named trigger functions run as invoker; runtime role must not own schema / disable triggers.
CREATE FUNCTION painter_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION '% is immutable',TG_TABLE_NAME USING ERRCODE='23514'; END $$;

CREATE FUNCTION painter_keep_owner() RETURNS trigger LANGUAGE plpgsql VOLATILE AS $$
BEGIN
 IF TG_OP='UPDATE' AND NEW.role IS NOT DISTINCT FROM OLD.role AND NEW.disabled_at_ms IS NOT DISTINCT FROM OLD.disabled_at_ms THEN RETURN NEW; END IF;
 IF OLD.role='owner' AND OLD.disabled_at_ms IS NULL THEN
  IF TG_OP='DELETE' OR NEW.role<>'owner' OR NEW.disabled_at_ms IS NOT NULL THEN
   PERFORM 1 FROM policy_barrier WHERE id=1 FOR UPDATE;
   IF NOT FOUND THEN RAISE EXCEPTION 'policy barrier missing' USING ERRCODE='23514'; END IF;
   IF NOT EXISTS(SELECT 1 FROM users WHERE role='owner' AND disabled_at_ms IS NULL AND id<>OLD.id) THEN
    RAISE EXCEPTION 'cannot revoke last active owner' USING ERRCODE='23514';
   END IF;
  END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER users_owner_guard BEFORE UPDATE OF role,disabled_at_ms OR DELETE ON users FOR EACH ROW EXECUTE FUNCTION painter_keep_owner();

CREATE FUNCTION painter_policy_changed() RETURNS trigger LANGUAGE plpgsql VOLATILE AS $$
BEGIN
 IF TG_TABLE_NAME='users' THEN
  IF NEW.role IS NOT DISTINCT FROM OLD.role AND NEW.disabled_at_ms IS NOT DISTINCT FROM OLD.disabled_at_ms THEN RETURN NEW; END IF;
 END IF;
 UPDATE policy_barrier SET version=version+1 WHERE id=1;
 IF NOT FOUND THEN RAISE EXCEPTION 'policy barrier missing' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
