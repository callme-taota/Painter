-- Independent short, plain-text content. Saving a draft never changes its
-- public snapshot. Publication timestamps survive withdrawal for stable order.
CREATE TABLE moments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 draft_text TEXT NOT NULL CHECK(char_length(draft_text) BETWEEN 1 AND 500 AND btrim(draft_text)<>''),
 public_text TEXT CHECK(public_text IS NULL OR (char_length(public_text) BETWEEN 1 AND 500 AND btrim(public_text)<>'')),
 first_published_at_ms BIGINT,
 published_at_ms BIGINT,
 created_at_ms BIGINT NOT NULL CHECK(created_at_ms>=0),
 updated_at_ms BIGINT NOT NULL CHECK(updated_at_ms>=created_at_ms),
 deleted_at_ms BIGINT,
 CHECK((first_published_at_ms IS NULL)=(published_at_ms IS NULL)),
 CHECK(first_published_at_ms IS NULL OR (first_published_at_ms>=0 AND published_at_ms>=first_published_at_ms)),
 CHECK(public_text IS NULL OR first_published_at_ms IS NOT NULL),
 CHECK(deleted_at_ms IS NULL OR (deleted_at_ms>=created_at_ms AND public_text IS NULL))
);
CREATE INDEX moments_author_id ON moments(author_user_id,id DESC);
CREATE INDEX moments_public_order ON moments(first_published_at_ms DESC,id DESC)
 WHERE public_text IS NOT NULL AND deleted_at_ms IS NULL;
CREATE INDEX moments_public_author_order ON moments(author_user_id,first_published_at_ms DESC,id DESC)
 WHERE public_text IS NOT NULL AND deleted_at_ms IS NULL;

-- Resource-specific idempotent authorization relies on a stable author. A
-- future administrative bulk update cannot silently transfer that identity.
CREATE FUNCTION painter_moment_identity_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.id<>OLD.id OR NEW.author_user_id<>OLD.author_user_id THEN
  RAISE EXCEPTION 'moment identity and author are immutable' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER moments_identity_guard BEFORE UPDATE OF id,author_user_id ON moments
 FOR EACH ROW EXECUTE FUNCTION painter_moment_identity_guard();

-- The public query surface deliberately contains no draft or mutation version.
-- Like public_posts, disabling an author blocks sessions/writes but preserves
-- already published content; explicit withdrawal/deletion controls visibility.
CREATE VIEW public_moments AS
 SELECT id,author_user_id,public_text AS text,first_published_at_ms,published_at_ms
 FROM moments WHERE public_text IS NOT NULL AND deleted_at_ms IS NULL;

